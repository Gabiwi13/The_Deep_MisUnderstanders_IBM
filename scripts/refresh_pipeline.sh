#!/usr/bin/env bash
# Re-run the whole pipeline when the upstream data changed. Meant for a cron on the LinuxONE instance,
# but it works anywhere the repo and its dependencies are available.
#
#   scripts/refresh_pipeline.sh            # only if scripts/check_updates.py sees a change
#   scripts/refresh_pipeline.sh --force    # run anyway (demo, or after editing a script)
#
# Steps: pull -> detect change -> download -> prepare features -> accept new baseline ->
#        run notebooks headless -> compare results -> commit on a refresh/<date> branch.
#
# Settings (environment variables):
#   NOTEBOOK_RUN   command that executes a notebook in place. Default: jupyter nbconvert on this host.
#                  On LinuxONE the notebooks live in the Jupyter container, so something like
#                  NOTEBOOK_RUN='docker exec <container> jupyter nbconvert --to notebook --execute --inplace'
#                  (the repo must be visible inside the container at the same path).
#   NOTEBOOKS      notebooks to run, in order. Default: the three that use the refreshed data.
#   PUSH=1         push the refresh branch to origin (needs git credentials on this machine).
#
# Cron example (every 30 minutes; flock stops two runs from overlapping):
#   */30 * * * * cd /path/to/repo && flock -n /tmp/refresh.lock scripts/refresh_pipeline.sh >> refresh.log 2>&1
set -euo pipefail
cd "$(dirname "$0")/.."

FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1
NOTEBOOK_RUN=${NOTEBOOK_RUN:-jupyter nbconvert --to notebook --execute --inplace}
NOTEBOOKS=${NOTEBOOKS:-"notebooks/03_risk_model.ipynb notebooks/03b_outlook_2030.ipynb notebooks/04_crime_trends_profile.ipynb"}
log() { echo "[$(date -u +%FT%TZ)] $*"; }

log "pulling latest code"
git pull --ff-only -q || log "git pull failed, continuing with the local copy"

set +e
python3 scripts/check_updates.py --report /tmp/update_report.md > /dev/null
code=$?
set -e
if [ "$FORCE" = "0" ]; then
  case $code in
    0) log "no changes upstream, nothing to do"; exit 0 ;;
    2) log "some sources could not be reached, not refreshing"; cat /tmp/update_report.md; exit 0 ;;
    1) log "upstream changed:"; cat /tmp/update_report.md ;;
    *) log "check_updates.py crashed (exit $code)"; exit 1 ;;
  esac
fi

branch="refresh/$(date -u +%Y%m%d-%H%M)"
git checkout -q -b "$branch"
cp results/block_risk.csv /tmp/block_risk_before.csv

log "downloading data"
python3 scripts/download_data.py
log "building features"
python3 scripts/prepare_features.py
python3 scripts/check_updates.py --accept

for nb in $NOTEBOOKS; do
  log "running $nb"
  $NOTEBOOK_RUN "$nb"
done

log "comparing results"
{
  echo "# Refresh $(date -u +%F\ %H:%M) UTC"
  echo; echo "## What changed upstream"; echo
  cat /tmp/update_report.md
  echo; echo "## Model results"; echo
  python3 scripts/compare_results.py /tmp/block_risk_before.csv results/block_risk.csv
} > results/refresh_report.md
cat results/refresh_report.md

git add -A data results
git commit -q -m "Refresh data and results after upstream change" -m "Generated by scripts/refresh_pipeline.sh. See results/refresh_report.md."
log "committed on $branch"
if [ "${PUSH:-0}" = "1" ]; then
  git push -q -u origin "$branch" && log "pushed $branch"
fi
